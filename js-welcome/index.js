// !== ("не равно, "not equal")
// Бинарный оператор, возвращает Boolean 
// Проверяет, оба ли операнда НЕ равны друг другу 
// Если операнды не равны междв собой- возвращается true 
// Если операнды равны между собой - возврщается false

// Задача. Дано число. Проверить, не ровно ли оно 5.

const number = 15;

if(number !== 5) {
  console.log(number + ' не равен 5');
} else {
  console.log(number + ' равен 5');
}
